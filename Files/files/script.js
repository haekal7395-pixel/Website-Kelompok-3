const $ = (s) => document.querySelector(s);
const hues = [168, 190, 152, 205, 42, 160, 180, 28, 196, 140];
let kec = "Semua";
let kata = "";

/* ---------- Statistik hero ---------- */
$("#stTotal").textContent = MASJID.length;
$("#stKec").textContent = new Set(MASJID.map((m) => m.kec)).size;
$("#st24").textContent = MASJID.filter((m) => m.jam === "24 jam").length;

/* ---------- Chip kecamatan ---------- */
const daftarKec = ["Semua", ...new Set(MASJID.map((m) => m.kec))];

$("#chips").innerHTML = daftarKec
  .map((k) => {
    const n =
      k === "Semua" ? MASJID.length : MASJID.filter((m) => m.kec === k).length;
    return `<button class="chip" data-k="${k}" aria-pressed="${k === kec}">${k}<small>${n}</small></button>`;
  })
  .join("");

$("#chips").addEventListener("click", (e) => {
  const b = e.target.closest(".chip");
  if (!b) return;
  kec = b.dataset.k;
  document
    .querySelectorAll(".chip")
    .forEach((c) => c.setAttribute("aria-pressed", c.dataset.k === kec));
  render();
});

/* ---------- Pencarian ---------- */
$("#q").addEventListener("input", (e) => {
  kata = e.target.value.trim().toLowerCase();
  render();
});

/* ---------- Helper ---------- */
const pin =
  '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M12 21s7-6.2 7-11.5A7 7 0 005 9.5C5 14.8 12 21 12 21z"/><circle cx="12" cy="9.5" r="2.5"/></svg>';

const mapUrl = (m) =>
  `https://www.google.com/maps/search/?api=1&query=${m.lat},${m.lng}`;

/* Foto untuk kartu. Jika gagal dimuat, gambar dihapus
   sehingga banner kembali ke gradien. */
const fotoKartu = (m) =>
  m.foto
    ? `<img src="${m.foto}" alt="Foto ${m.nama}" loading="lazy" onerror="this.remove()">`
    : "";

/* ---------- Render daftar kartu ---------- */
function render() {
  const hasil = MASJID.map((m, i) => ({ ...m, i })).filter(
    (m) =>
      (kec === "Semua" || m.kec === kec) &&
      (m.nama + " " + m.alamat + " " + m.kec + " " + m.tags.join(" "))
        .toLowerCase()
        .includes(kata),
  );

  $("#count").textContent =
    `Menampilkan ${hasil.length} dari ${MASJID.length} masjid`;

  $("#grid").innerHTML = hasil.length
    ? hasil
        .map(
          (m) => `
      <article class="card">
        <div class="art" style="--h:${hues[m.i]}">
          ${fotoKartu(m)}
          <span class="pill">Kec. ${m.kec}</span>
          ${m.foto ? "" : '<svg viewBox="0 0 120 90"><use href="#masjid"/></svg>'}
        </div>
        <div class="body">
          <h3>${m.nama}</h3>
          <div class="addr">${pin}<span>${m.alamat}</span></div>
          <div class="tags">${m.tags.map((t) => `<span>${t}</span>`).join("")}</div>
          <div class="foot">
            <div class="jam">Buka<br><b>${m.jam}</b></div>
            <button class="btn" data-i="${m.i}">Lihat detail</button>
          </div>
        </div>
      </article>`,
        )
        .join("")
    : `<div class="empty"><b>Masjid tidak ditemukan</b>Coba kata kunci lain atau pilih kecamatan “Semua”.</div>`;
}

/* ---------- Dialog detail ---------- */
const dlg = $("#dlg");

$("#grid").addEventListener("click", (e) => {
  const b = e.target.closest("[data-i]");
  if (!b) return;
  const m = MASJID[b.dataset.i];

  /* Banner dialog: hapus foto lama, pasang foto masjid ini */
  const dArt = $("#dArt");
  dArt.style.setProperty("--h", hues[b.dataset.i]);
  dArt.querySelector("img")?.remove();
  const ilustrasi = dArt.querySelector("svg");
  if (ilustrasi) ilustrasi.style.display = m.foto ? "none" : "";
  if (m.foto) {
    const img = document.createElement("img");
    img.src = m.foto;
    img.alt = "Foto " + m.nama;
    img.onerror = () => {
      img.remove();
      if (ilustrasi) ilustrasi.style.display = "";
    };
    dArt.prepend(img);
  }

  $("#dTitle").textContent = m.nama;
  $("#dNote").textContent = m.catatan;
  $("#dList").innerHTML =
    `<li><b>Alamat</b><span>${m.alamat}, Kec. ${m.kec}, Salatiga</span></li>` +
    `<li><b>Jam buka</b><span>${m.jam}</span></li>` +
    (m.tel ? `<li><b>Telepon</b><span>${m.tel}</span></li>` : "");
  $("#dMap").href = mapUrl(m);

  $("#dCopy").textContent = "Salin alamat";
  $("#dCopy").onclick = async () => {
    try {
      await navigator.clipboard.writeText(`${m.nama}, ${m.alamat}, Salatiga`);
      $("#dCopy").textContent = "Tersalin";
    } catch {
      $("#dCopy").textContent = "Gagal menyalin";
    }
  };

  dlg.showModal();
});

$("#dClose").onclick = () => dlg.close();
dlg.addEventListener("click", (e) => {
  if (e.target === dlg) dlg.close();
});

/* ---------- Tampilkan pertama kali ---------- */
render();